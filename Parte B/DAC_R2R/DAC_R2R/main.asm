.include "m328pdef.inc"

.equ F_CPU = 16000000
.equ BAUD = 9600
.equ BPS = (F_CPU/16/BAUD)-1

.def muestra = r16
.def temporal = r17
.def indice = r18
.def cero = r22

.cseg
.org 0x0000
    rjmp inicio

.org 0x0016
    rjmp ISR_TIMER1_COMPA

.org 0x0100

inicio:
    ldi temporal, HIGH(RAMEND)
    out SPH, temporal
    ldi temporal, LOW(RAMEND)
    out SPL, temporal
    ldi temporal, 0b00111111
    out DDRB, temporal
    ldi temporal, 0b00000011
    out DDRC, temporal
    ldi temporal, (1<<DDD3)
    out DDRD, temporal
    clr temporal
    out PORTB, temporal
    out PORTC, temporal

    ldi muestra, LOW(BPS)
    ldi temporal, HIGH(BPS)
    rcall iniciar_uart

    ldi temporal, (1<<COM2B1)|(1<<WGM21)|(1<<WGM20)
    sts TCCR2A, temporal
    ldi temporal, (1<<CS20)
    sts TCCR2B, temporal
    clr temporal
    sts OCR2B, temporal

    clr temporal
    sts TCCR1A, temporal
    sts TCNT1H, temporal
    sts TCNT1L, temporal
    ldi temporal, HIGH(999)
    sts OCR1AH, temporal
    ldi temporal, LOW(999)
    sts OCR1AL, temporal
    ldi temporal, (1<<WGM12)|(1<<CS11)|(1<<CS10)
    sts TCCR1B, temporal
    ldi temporal, (1<<OCIE1A)
    sts TIMSK1, temporal

    clr indice
    ldi ZH, HIGH(menu*2)
    ldi ZL, LOW(menu*2)
    rcall enviar_cadena
    sei

principal:
    rjmp principal

iniciar_uart:
    sts UBRR0L, muestra
    sts UBRR0H, temporal
    clr temporal
    sts UCSR0A, temporal
    ldi temporal, (1<<RXEN0)|(1<<TXEN0)
    sts UCSR0B, temporal
    ldi temporal, (1<<UCSZ01)|(1<<UCSZ00)
    sts UCSR0C, temporal
    ret

enviar_cadena:
    lpm muestra, Z+
    tst muestra
    breq fin_cadena
    rcall enviar_caracter
    rjmp enviar_cadena

fin_cadena:
    ret

enviar_caracter:
    lds temporal, UCSR0A
    sbrs temporal, UDRE0
    rjmp enviar_caracter
    sts UDR0, muestra
    ret

ISR_TIMER1_COMPA:
    push muestra
    in muestra, SREG
    push muestra
    push temporal
    push cero
    push ZL
    push ZH

    clr cero
    ldi ZH, HIGH(tabla_senal_1*2)
    ldi ZL, LOW(tabla_senal_1*2)
    add ZL, indice
    adc ZH, cero
    lpm muestra, Z

    mov temporal, muestra
    andi temporal, 0b00000011
    out PORTC, temporal
    mov temporal, muestra
    lsr temporal
    lsr temporal
    out PORTB, temporal
    sts OCR2B, muestra
    inc indice

    pop ZH
    pop ZL
    pop cero
    pop temporal
    pop muestra
    out SREG, muestra
    pop muestra
    reti

